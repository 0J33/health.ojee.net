#!/usr/bin/env node
/* Optical centring of the icons (web/js/optical.js, web/css/optical.css).

   Each icon is drawn at 240 px in a headless Chrome and the centre of its ink found. An icon whose
   ink is heavier on one side (a send plane, a flag, a download arrow over its tray, a heart's
   lobes) looks off-centre in a round button even when its box is centred: it is moved half the way
   from its ink's centre to the box's, at most 1.25 of its 24 units (5 %), and only when that is a
   quarter unit or more. Icons drawn already balanced (the play triangle) come out unmoved.

     PLAYWRIGHT=<dir with node_modules/playwright-core> CHROME=<chrome binary> node scripts/measure-optical.mjs

   Writes both files; the round holders the nudge applies in are listed in HOLDERS below. */

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const HOLDERS = ['.pm__play', '.b-play', '.mview__x', '.mview__nav', '.iconbtn', '.infotip__b', '.pp-ib', '.ib', '.wcard__ic', '.mrow__ic', '.insight__ic', '.empty__ic',
  '.trn-quick__ic', '.trn-ses__ic', '.cx-tile__ic', '.xrow__ic', '.verdict__ic', '.hl-sec__ic', '.me-pcard__av', '.bto-cmp__x', '.map__gap', '.skwx__ic', '.mebtn', '.bt__ic', '.mus__btn'];

const require = createRequire(join(process.env.PLAYWRIGHT || root, 'node_modules/'));
const { chromium } = require('playwright-core');
const { icon, iconNames } = await import(pathToFileURL(join(root, 'web/js/icons.js')));
const svgs = Object.fromEntries(iconNames().map((n) => [n, icon(n)]));
const b = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const p = await b.newPage();
await p.setContent('<div></div>');
const ink = await p.evaluate(async (svgs) => {
  const S = 240; const res = {};
  for (const [n, s] of Object.entries(svgs)) {
    const el = new DOMParser().parseFromString(s.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240" ').replace(/currentColor/g, 'black'), 'image/svg+xml').documentElement;
    if (!el.getAttribute('fill')) el.setAttribute('fill', 'black');
    const img = new Image(); img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(new XMLSerializer().serializeToString(el))}`;
    await img.decode().catch(() => null);
    const c = document.createElement('canvas'); c.width = S; c.height = S; const x = c.getContext('2d'); x.drawImage(img, 0, 0, S, S);
    const d = x.getImageData(0, 0, S, S).data;
    let m = 0; let sx = 0; let sy = 0;
    for (let i = 0; i < S * S; i += 1) { const a = d[i * 4 + 3]; if (!a) continue; m += a; sx += a * ((i % S) + 0.5); sy += a * (((i / S) | 0) + 0.5); }
    res[n] = m ? [(sx / m) * (24 / S) - 12, (sy / m) * (24 / S) - 12] : null;
  }
  return res;
}, svgs);
await b.close();

const r = (v) => Math.round(v * 20) / 20 || 0;
const c = (v) => Math.max(-1.25, Math.min(1.25, v));
const table = {};
for (const [n, v] of Object.entries(ink).sort()) {
  if (!v) continue;
  let dx = r(c(-0.5 * v[0])); let dy = r(c(-0.5 * v[1]));
  if (Math.abs(dx) < 0.25) dx = 0;
  if (Math.abs(dy) < 0.25) dy = 0;
  if (dx || dy) table[n] = [dx, dy];
}
writeFileSync(join(root, 'web/js/optical.js'), `/* Optical centring: how far to move each icon, in units of its 24 grid, so it looks centred in a
   round button or holder (css/optical.css). An icon whose ink is heavier on one side (a send
   plane, a flag, a download arrow over its tray, a heart's lobes) looks off-centre even when its box
   is centred; each is moved half the way from its ink's centre to the box's centre, at most 1.25
   (5 %), and only when that is a quarter unit or more. GENERATED by scripts/measure-optical.mjs;
   run it again when icons are added. */

export const OPTICAL = {
${Object.entries(table).map(([n, [x, y]]) => `  ${JSON.stringify(n)}: [${x}, ${y}],`).join('\n')}
};
`);
writeFileSync(join(root, 'web/css/optical.css'), `/* Optical centring (web/js/optical.js): an icon alone in a round button or holder, or in a button
   that is only its icon, is moved so it looks centred, not only measures centred. GENERATED by
   scripts/measure-optical.mjs from the icons' ink; the holders are listed there by hand. */

:is(${HOLDERS.join(', ')}, button[aria-label], a[aria-label]) > .ic:only-child { translate: var(--ox, 0) var(--oy, 0); }

/* A filled play triangle (the video tile's, a routine's start) has its weight further left than the
   outline one these are measured on: its centre of mass on the button's. */
.pm__play .ic, .b-play .ic { --ox: 5.4%; --oy: 0%; }

${Object.entries(table).map(([n, [x, y]]) => `.ic[data-ic="${n}"] { --ox: ${(x / 0.24).toFixed(2)}%; --oy: ${(y / 0.24).toFixed(2)}%; }`).join('\n')}
`);
console.log(`${Object.keys(table).length} icons moved`);
